"""Generate plain-English business insights from the analytics result files.

No API key needed: findings are built from the numbers with simple rules.
Run:  python src/ai_insights.py
Output: reports/ai_insights.md
"""
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "powerbi" / "data"
OUT = ROOT / "reports" / "ai_insights.md"


def cr(x):
    """Format a rupee amount in crore (1 Cr = 10 million)."""
    return f"₹{x / 1e7:,.1f} Cr"


def load(name):
    return pd.read_csv(DATA / name)


def main():
    monthly = load("monthly_sales_trends.csv")
    monthly = monthly[monthly["month"] < "2026-10"]  # drop the 1-day October 2026
    anomalies = load("sales_anomalies.csv")
    discounts = load("sql_discount_bands.csv")
    low_cat = load("sql_low_margin_categories.csv")
    brands = load("sql_brand_share.csv")
    repeat = load("sql_repeat_purchase_rate.csv").iloc[0]
    top10 = load("sql_top10pct_customer_share.csv").iloc[0, 0]
    rfm = load("rfm_customer_segments.csv")["segment"].value_counts()
    pay = load("sql_payment_methods.csv")
    ret = load("sql_high_return_products.csv")

    findings = []  # (title, what we see, action)

    # 1. Revenue trend: compare last 6 months with the 6 months before
    last6 = monthly["total_revenue"].tail(6).mean()
    prev6 = monthly["total_revenue"].iloc[-12:-6].mean()
    change = (last6 / prev6 - 1) * 100
    direction = "fell" if change < 0 else "grew"
    findings.append((
        "Revenue trend",
        f"Average monthly revenue over the last 6 months was {cr(last6)}, which "
        f"{direction} {abs(change):.1f}% compared with the 6 months before.",
        "Check which categories and regions drive the change before planning "
        "next quarter's targets." if change < 0 else
        "Keep the campaigns and channels that supported this growth."))

    # 2. Discounts and margin
    d = discounts.assign(margin=discounts["profit"] / discounts["revenue"] * 100)
    d = d[d["units_sold"] >= 1000]  # ignore tiny bands (the 0% band has only 12 units)
    best, worst = d.loc[d["margin"].idxmax()], d.loc[d["margin"].idxmin()]
    deep = d[d["discount_band"] == "30%+"].iloc[0]
    findings.append((
        "Discounts reduce profit",
        f"The {best['discount_band']} discount band earns a {best['margin']:.1f}% margin, "
        f"but the {worst['discount_band']} band earns only {worst['margin']:.1f}%. "
        f"The {deep['discount_band']} band still sold {int(deep['units_sold']):,} units.",
        "Cap discounts at 20% for most products and review every deal above 30%."))

    # 3. Low margin categories
    names = ", ".join(low_cat["category_name"])
    findings.append((
        "Low-margin categories",
        f"{names} are below the company average margin; "
        f"the lowest is {low_cat.iloc[0]['category_name']} at {low_cat.iloc[0]['margin_pct']}%.",
        "Review supplier costs and prices for these categories first."))

    # 4. Customers
    total = rfm.sum()
    findings.append((
        "Customer segments",
        f"{rfm['Champions']:,} customers are Champions, but {rfm['At Risk']:,} are At Risk "
        f"and {rfm['Lost Customers']:,} are Lost ({rfm['Lost Customers'] / total * 100:.0f}% of "
        f"segmented customers). The repeat purchase rate is {repeat['repeat_purchase_rate_pct']}% "
        f"and the top 10% of customers bring {top10}% of revenue.",
        "Send win-back offers to At Risk customers and reward Champions with early access."))

    # 5. Anomalies
    hi = anomalies[anomalies["anomaly_status"] == "Unusually High"]
    lo = anomalies[anomalies["anomaly_status"] == "Unusually Low"]
    parts = [f"{r['month'][:7]} was unusually high ({r['deviation_pct']:+.1f}% vs baseline)"
             for _, r in hi.iterrows()]
    parts += [f"{r['month'][:7]} was unusually low ({r['deviation_pct']:+.1f}% vs baseline)"
              for _, r in lo.iterrows()]
    findings.append((
        "Revenue anomalies",
        "; ".join(parts) + ".",
        "Find out what happened in those months (campaigns, stock, delivery issues) "
        "and repeat or avoid it."))

    # 6. Operations
    worst_pay = pay.loc[pay["failed_payment_rate_pct"].idxmax()]
    findings.append((
        "Payments and returns",
        f"About {pay['failed_payments'].sum() / pay['total_payments'].sum() * 100:.1f}% of payments fail; "
        f"{worst_pay['method']} is highest at {worst_pay['failed_payment_rate_pct']}%. "
        f"Return rates reach {ret['return_rate_pct'].max()}% for individual products "
        f"(e.g. {ret.iloc[0]['product_name']}).",
        "Investigate the payment failure rate and check quality or descriptions "
        "of the high-return products."))

    lines = ["# AI Business Insights", "",
             "> Generated by `src/ai_insights.py` from the analytics result files. "
             "Data is synthetic. Amounts in ₹ crore (1 Cr = 10 million).", "",
             f"**Top brand:** {brands.iloc[0]['brand']} ({brands.iloc[0]['revenue_share_pct']}% of revenue)", ""]
    for i, (title, seen, action) in enumerate(findings, 1):
        lines += [f"## {i}. {title}", f"**Finding:** {seen}", "",
                  f"**Recommended action:** {action}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Saved {OUT}")


if __name__ == "__main__":
    main()
